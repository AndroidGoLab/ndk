package media

import (
	"fmt"
)

// #include <media/NdkMediaError.h>
import "C"

// MediaStatus is an NDK media_status_t value.
type MediaStatus int

const (
	MEDIA_OK = MediaStatus(C.AMEDIA_OK)

	ERROR_BASE              = MediaStatus(C.AMEDIA_ERROR_BASE)
	ERROR_UNKNOWN           = MediaStatus(C.AMEDIA_ERROR_UNKNOWN)
	ERROR_MALFORMED         = MediaStatus(C.AMEDIA_ERROR_MALFORMED)
	ERROR_UNSUPPORTED       = MediaStatus(C.AMEDIA_ERROR_UNSUPPORTED)
	ERROR_INVALID_OBJECT    = MediaStatus(C.AMEDIA_ERROR_INVALID_OBJECT)
	ERROR_INVALID_PARAMETER = MediaStatus(C.AMEDIA_ERROR_INVALID_PARAMETER)
	ERROR_INVALID_OPERATION = MediaStatus(C.AMEDIA_ERROR_INVALID_OPERATION)

	DRM_ERROR_BASE         = MediaStatus(C.AMEDIA_DRM_ERROR_BASE)
	DRM_NOT_PROVISIONED    = MediaStatus(C.AMEDIA_DRM_NOT_PROVISIONED)
	DRM_RESOURCE_BUSY      = MediaStatus(C.AMEDIA_DRM_RESOURCE_BUSY)
	DRM_DEVICE_REVOKED     = MediaStatus(C.AMEDIA_DRM_DEVICE_REVOKED)
	DRM_SHORT_BUFFER       = MediaStatus(C.AMEDIA_DRM_SHORT_BUFFER)
	DRM_SESSION_NOT_OPENED = MediaStatus(C.AMEDIA_DRM_SESSION_NOT_OPENED)
	DRM_TAMPER_DETECTED    = MediaStatus(C.AMEDIA_DRM_TAMPER_DETECTED)
	DRM_VERIFY_FAILED      = MediaStatus(C.AMEDIA_DRM_VERIFY_FAILED)
	DRM_NEED_KEY           = MediaStatus(C.AMEDIA_DRM_NEED_KEY)
	DRM_LICENSE_EXPIRED    = MediaStatus(C.AMEDIA_DRM_LICENSE_EXPIRED)

	IMGREADER_ERROR_BASE          = MediaStatus(C.AMEDIA_IMGREADER_ERROR_BASE)
	IMGREADER_NO_BUFFER_AVAILABLE = MediaStatus(C.AMEDIA_IMGREADER_NO_BUFFER_AVAILABLE)
	IMGREADER_MAX_IMAGES_ACQUIRED = MediaStatus(C.AMEDIA_IMGREADER_MAX_IMAGES_ACQUIRED)
	IMGREADER_CANNOT_LOCK_IMAGE   = MediaStatus(C.AMEDIA_IMGREADER_CANNOT_LOCK_IMAGE)
	IMGREADER_CANNOT_UNLOCK_IMAGE = MediaStatus(C.AMEDIA_IMGREADER_CANNOT_UNLOCK_IMAGE)
	IMGREADER_IMAGE_NOT_LOCKED    = MediaStatus(C.AMEDIA_IMGREADER_IMAGE_NOT_LOCKED)
)

func (i MediaStatus) Error() string {
	switch i {
	case ERROR_UNKNOWN:
		return "ERROR_UNKNOWN"
	case ERROR_MALFORMED:
		return "ERROR_MALFORMED"
	case ERROR_UNSUPPORTED:
		return "ERROR_UNSUPPORTED"
	case ERROR_INVALID_OBJECT:
		return "ERROR_INVALID_OBJECT"
	case ERROR_INVALID_PARAMETER:
		return "ERROR_INVALID_PARAMETER"
	case ERROR_INVALID_OPERATION:
		return "ERROR_INVALID_OPERATION"
	case DRM_NOT_PROVISIONED:
		return "DRM_NOT_PROVISIONED"
	case DRM_RESOURCE_BUSY:
		return "DRM_RESOURCE_BUSY"
	case DRM_DEVICE_REVOKED:
		return "DRM_DEVICE_REVOKED"
	case DRM_SHORT_BUFFER:
		return "DRM_SHORT_BUFFER"
	case DRM_SESSION_NOT_OPENED:
		return "DRM_SESSION_NOT_OPENED"
	case DRM_TAMPER_DETECTED:
		return "DRM_TAMPER_DETECTED"
	case DRM_VERIFY_FAILED:
		return "DRM_VERIFY_FAILED"
	case DRM_NEED_KEY:
		return "DRM_NEED_KEY"
	case DRM_LICENSE_EXPIRED:
		return "DRM_LICENSE_EXPIRED"
	case IMGREADER_NO_BUFFER_AVAILABLE:
		return "IMGREADER_NO_BUFFER_AVAILABLE"
	case IMGREADER_MAX_IMAGES_ACQUIRED:
		return "IMGREADER_MAX_IMAGES_ACQUIRED"
	case IMGREADER_CANNOT_LOCK_IMAGE:
		return "IMGREADER_CANNOT_LOCK_IMAGE"
	case IMGREADER_CANNOT_UNLOCK_IMAGE:
		return "IMGREADER_CANNOT_UNLOCK_IMAGE"
	case IMGREADER_IMAGE_NOT_LOCKED:
		return "IMGREADER_IMAGE_NOT_LOCKED"
	}
	return fmt.Sprintf("ERROR_MEDIA_%d", i)
}

// CMediaStatusToError converts an NDK media status to the corresponding Go error.
func CMediaStatusToError(status C.media_status_t) error {
	if MediaStatus(status) != MEDIA_OK {
		return MediaStatus(status)
	}
	return nil
}
